    def gemSkilteplan(self):
        """Gemmer formularen paa den plan, der er valgt i listen."""
        if self._valgtPlanId is None:
            self.visBesked("Vaelg foerst en skilteplan i listen.", QMessageBox.Icon.Warning)
            return

        lag = self.skilteplanLag()
        f = self.planFeature(self._valgtPlanId)
        if lag is None or f is None:
            self.visBesked("Skilteplanen kunne ikke findes.", QMessageBox.Icon.Warning)
            return

        navn, start, slut = self.laesPlanFormular()
        if navn is None:
            return

        # Navnet skal stadig vaere unikt - men planen maa gerne beholde sit eget
        for anden in lag.getFeatures():
            if int(anden["planid"] or -1) == self._valgtPlanId:
                continue
            if anden["navn"] and str(anden["navn"]).strip().lower() == navn.lower():
                self.visBesked("Der findes allerede en anden skilteplan med "
                               "navnet '{}'.".format(navn), QMessageBox.Icon.Warning)
                return

        lag.startEditing()
        for felt, vaerdi in self.planVaerdier(navn, start, slut).items():
            f.setAttribute(felt, vaerdi)
        lag.updateFeature(f)

        if not lag.commitChanges():
            fejl = "\n".join(lag.commitErrors())
            lag.rollBack()
            self.visBesked("Aendringerne kunne ikke gemmes:\n{}".format(fejl),
                           QMessageBox.Icon.Critical)
            return

        gemt = self._valgtPlanId
        self.fillPlanList()

        stadig_synlig = False
        for i in range(self.planList.count()):
            if self.planList.item(i).data(Qt.ItemDataRole.UserRole) == gemt:
                self.planList.setCurrentRow(i)
                stadig_synlig = True
                break

        besked = "Skilteplanen '{}' er gemt.".format(navn)
        if not stadig_synlig:
            # Typisk efter at datoerne er aendret, saa planen skifter mellem
            # aktuel og tidligere - ellers ser den ud til at forsvinde
            besked += ("\n\nDen vises ikke laengere under '{}' - skift filter "
                       "for at se den.".format(self.cmbPlanFilter.currentText()))
        self.visBesked(besked, QMessageBox.Icon.Information)

    def laesPlanFormular(self):
        """Validerer formularen. Returnerer (navn, start, slut) eller (None,...)."""
        navn = self.editPlanNavn.text().strip()
        if not navn:
            self.visBesked("Skilteplanen skal have et navn.", QMessageBox.Icon.Warning)
            return None, None, None

        start = self.datePlanStart.date()
        slut = self.datePlanSlut.date()
        if slut < start:
            self.visBesked("Slutdatoen ligger foer startdatoen.", QMessageBox.Icon.Warning)
            return None, None, None
        return navn, start, slut

    def planVaerdier(self, navn, start, slut):
        """Formularens vaerdier som {feltnavn: vaerdi} - uden planid."""
        return {
            "navn": navn,
            "beskrivelse": self.editPlanBeskrivelse.toPlainText(),
            "startdato": start,
            "slutdato": slut,
            "kontaktorganisation": self.editPlanOrganisation.text(),
            "kontaktperson": self.editPlanKontakt.text(),
            "kontakttelefon": self.editPlanTelefon.text(),
            "kontaktmail": self.editPlanMail.text(),
        }

    def nulstilPlanFormular(self, forrige=None):
        """
        Tommer formularen. Kontaktoplysningerne overtages fra den seneste
        plan, da de sjaeldent skifter mellem planer i samme organisation.
        """
        self.editPlanNavn.clear()
        self.editPlanBeskrivelse.clear()
        self.datePlanStart.setDate(QDate.currentDate())
        self.datePlanSlut.setDate(QDate.currentDate().addDays(30))

        if forrige is not None:
            self.editPlanOrganisation.setText(forrige["kontaktorganisation"] or "")
            self.editPlanKontakt.setText(forrige["kontaktperson"] or "")
            self.editPlanTelefon.setText(forrige["kontakttelefon"] or "")
            self.editPlanMail.setText(forrige["kontaktmail"] or "")

        self.setPlanBtnState()

    def opretSkilteplan(self):
        """Opretter en ny raekke i skilteplan-tabellen."""
        lag = self.skilteplanLag()
        if lag is None:
            self.visBesked("Tilknyt foerst et lag til rollen 'skilteplan' "
                           "paa fanebladet 'Opsaetning'.", QMessageBox.Icon.Warning)
            return

        navn, start, slut = self.laesPlanFormular()
        if navn is None:
            return

        # planid saettes her og ikke af databasen: kolonnen er 'integer' netop
        # for at opfoere sig ens i PostGIS, GeoPackage og FileGDB
        hoejeste = 0
        for f in lag.getFeatures():
            if f["navn"] and str(f["navn"]).strip().lower() == navn.lower():
                self.visBesked("Der findes allerede en skilteplan med navnet "
                               "'{}'.".format(navn), QMessageBox.Icon.Warning)
                return
            vaerdi = f["planid"]
            if vaerdi is not None and int(vaerdi) > hoejeste:
                hoejeste = int(vaerdi)

        feature = QgsFeature()
        feature.setFields(lag.fields(), True)
        feature.setAttribute("planid", hoejeste + 1)
        for felt, vaerdi in self.planVaerdier(navn, start, slut).items():
            feature.setAttribute(felt, vaerdi)

        lag.startEditing()
        if not lag.addFeature(feature):
            lag.rollBack()
            self.visBesked("Skilteplanen kunne ikke tilfoejes.", QMessageBox.Icon.Critical)
            return

        if not lag.commitChanges():
            fejl = "\n".join(lag.commitErrors())
            lag.rollBack()
            self.visBesked("Skilteplanen kunne ikke gemmes:\n{}".format(fejl),
                           QMessageBox.Icon.Critical)
            return

        self.fillPlanList()
