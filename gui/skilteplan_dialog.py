    def autoudfyldRoller(self, overskriv=False):
        """
        Udfylder rollevaelgere med lag, der allerede hedder det forventede
        ('skilte', 'skiltetyper', 'skilteplan').

        Roerer som udgangspunkt kun tomme vaelgere, saa en gemt tilknytning
        eller et aktivt valg ikke bliver overskrevet.
        """
        project = QgsProject.instance()
        udfyldt = []

        for rolle, combo in self.rolleCombos.items():
            if combo.currentLayer() is not None and not overskriv:
                continue

            kandidater = []
            for lag in project.mapLayers().values():
                if not isinstance(lag, QgsVectorLayer):
                    continue
                if lag.name().strip().lower() != rolle.lower():
                    continue
                # Skal kunne staa i vaelgeren - ellers ville setLayer()
                # fejle stille, fordi laget er filtreret fra i modellen
                if skema.harGeometri(rolle):
                    if lag.geometryType() != Qgis.GeometryType.Point:
                        continue
                elif lag.geometryType() != Qgis.GeometryType.Null:
                    continue
                kandidater.append(lag)

            if not kandidater:
                continue

            # Ved flere lag med samme navn foretraekkes et, der validerer rent
            kandidater.sort(key=lambda l: 0 if skema.validerLag(l, rolle).ok else 1)
            combo.setLayer(kandidater[0])
            udfyldt.append(rolle)

        return udfyldt

    def tilknyttedeLag(self):
        """{rolle: QgsVectorLayer} for de roller, der er udpeget et lag til."""
        valgte = {}
        for rolle, combo in self.rolleCombos.items():
            lag = combo.currentLayer()
            if lag is not None:
                valgte[rolle] = lag
        return valgte

    def saetTilknytning(self, lagIdPrRolle):
        """Genskaber en gemt tilknytning ud fra lag-id'er."""
        for rolle, lagid in (lagIdPrRolle or {}).items():
            combo = self.rolleCombos.get(rolle)
            if combo is None or not lagid:
                continue
            lag = QgsProject.instance().mapLayer(lagid)
            if lag is not None:
                combo.setLayer(lag)

    def validerTilknytning(self):
        """Validerer de udpegede lag og viser resultatet."""
        valgte = self.tilknyttedeLag()

        if not valgte:
            self.txtValidering.setPlainText(
                "Ingen lag udpeget endnu.\n\n"
                "Hent skiltelagene ind i projektet fra den datakilde, du "
                "bruger, og vaelg dem herover.")
            return False

        alt_ok = True
        linjer = []
        for rolle in skema.ROLLER:
            lag = valgte.get(rolle)
            if lag is None:
                linjer.append("- {}: intet lag valgt".format(rolle))
                alt_ok = False
                continue

            res = skema.validerLag(lag, rolle)
            mark = "OK" if res.ok else "FEJL"
            linjer.append("{} {}: {}".format(mark, rolle, lag.name()))
            for f in res.fejl:
                linjer.append("     ! {}".format(f))
            for a in res.advarsler:
                linjer.append("     ? {}".format(a))
            if not res.ok:
                alt_ok = False

        if alt_ok:
            linjer.append("")
            linjer.append("Alle lag kan bruges.")

        self.txtValidering.setPlainText("\n".join(linjer))
        self.setEnableBtnState()
        return alt_ok

    def skilteplanLag(self):
        """Laget bag skilteplanerne - den tilknyttede rolle, ellers paa navn."""
        lag = self.cmbLagSkilteplan.currentLayer()
        if lag is not None and lag.isValid():
            return lag

        for kandidat in QgsProject.instance().mapLayers().values():
            if kandidat.name() == "skilteplan" and kandidat.isValid():
                return kandidat
        return None

    def fillPlanList(self):
        """Viser de eksisterende skilteplaner og forbereder formularen."""
        self.planList.clear()
        lag = self.skilteplanLag()
        if lag is None:
            self._sidstePlan = None
            self.fravaelgPlan()
            self.nulstilPlanFormular()
            return

        filter_tekst = self.cmbPlanFilter.currentText()
        i_dag = QDate.currentDate()

        sidste = None
        for f in sorted(lag.getFeatures(), key=lambda x: x["planid"] or 0):
            start = self.tilQDate(f["startdato"])
            slut = self.tilQDate(f["slutdato"])

            # Aktuel = slutdato i dag eller senere. Det er samme afgraensning
            # som attributformularen bruger, naar den viser valgbare planer.
            # En plan uden slutdato regnes som aktuel.
            aktuel = slut is None or slut >= i_dag
            if filter_tekst == "Aktuelle" and not aktuel:
                continue
            if filter_tekst == "Tidligere" and aktuel:
                continue

            navn = f["navn"] or "(uden navn)"
            periode = "   {} - {}".format(
                start.toString("dd-MM-yyyy") if start else "?",
                slut.toString("dd-MM-yyyy") if slut else "?")
            item = QListWidgetItem("{}{}".format(navn, periode))
            item.setData(Qt.ItemDataRole.UserRole, f["planid"])
            self.planList.addItem(item)
            sidste = f

        self._sidstePlan = sidste
        self.fravaelgPlan()
        self.nulstilPlanFormular(sidste)

