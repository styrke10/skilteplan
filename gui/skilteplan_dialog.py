    def deleteSign(self):
        name, desc = self.valgtSkilt()
        if not name:
            return

        layer = self.skiltetyperLag()
        found = layer is not None

        if found:
            layer.startEditing()
            request = QgsFeatureRequest().setFilterExpression('"skiltenavn" = \'{}\''.format(name))

            # Iterate over matching features and delete them
            for feature in layer.getFeatures(request):
                msgBox = QMessageBox()
                msgBox.setIcon(QMessageBox.Icon.Warning)
                msgBox.setText("Vil du slette skilt '{} - {}'".format(name,desc))
                msgBox.setStandardButtons(QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No)
                response = msgBox.exec()
                if response == QMessageBox.StandardButton.Yes:
                    layer.deleteFeature(feature.id())
                    # Delete SVG file
                    delpath = os.path.join(self.path_sign_graphics.filePath(),'.'.join((name,'svg')))
                    if os.path.isfile(delpath):
                        os.remove(delpath)

            layer.commitChanges()
            
            # Refresh sign list on parent dialog
            self.fillSignList()
