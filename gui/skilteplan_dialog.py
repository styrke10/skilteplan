    def planFeature(self, planid):
        """Henter en skilteplan paa planid."""
        lag = self.skilteplanLag()
        if lag is None or planid is None:
            return None
        for f in lag.getFeatures():
            if f["planid"] is not None and int(f["planid"]) == int(planid):
                return f
        return None

    def indlaesValgtPlan(self):
        """Fylder formularen med den valgte plan, saa den kan rettes."""
        item = self.planList.currentItem()
        if item is None:
            self._valgtPlanId = None
            self.btnGemPlan.setEnabled(False)
            self.setPlanBtnState()
            return

        f = self.planFeature(item.data(Qt.ItemDataRole.UserRole))
        if f is None:
            self._valgtPlanId = None
            self.btnGemPlan.setEnabled(False)
            self.setPlanBtnState()
            return

        self._valgtPlanId = int(f["planid"])
        self.editPlanNavn.setText(f["navn"] or "")
        self.editPlanBeskrivelse.setPlainText(f["beskrivelse"] or "")
        self.saetDato(self.datePlanStart, f["startdato"])
        self.saetDato(self.datePlanSlut, f["slutdato"])
        self.editPlanOrganisation.setText(f["kontaktorganisation"] or "")
        self.editPlanKontakt.setText(f["kontaktperson"] or "")
        self.editPlanTelefon.setText(f["kontakttelefon"] or "")
        self.editPlanMail.setText(f["kontaktmail"] or "")
        self.btnGemPlan.setEnabled(True)
        self.setPlanBtnState()

    @staticmethod
    def tilQDate(vaerdi):
        """
        Datofelter kommer som QDate fra nogle providere og som tekst fra andre.
        Returnerer None, hvis vaerdien ikke kan tydes.
        """
        if vaerdi is None:
            return None
        if isinstance(vaerdi, QDate):
            return vaerdi if vaerdi.isValid() else None
        for form in ("yyyy-MM-dd", "dd-MM-yyyy"):
            d = QDate.fromString(str(vaerdi), form)
            if d.isValid():
                return d
        return None

    def saetDato(self, widget, vaerdi):
        d = self.tilQDate(vaerdi)
        widget.setDate(d if d is not None else QDate.currentDate())

