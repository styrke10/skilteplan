    def rollerErGyldige(self):
        """True hvis alle tre roller har et lag, der validerer uden fejl."""
        valgte = self.tilknyttedeLag()
        if len(valgte) < len(skema.ROLLER):
            return False
        return all(skema.validerLag(lag, rolle).ok
                   for rolle, lag in valgte.items())

    def opsaetRolleCombos(self):
        """Klargoer de tre lagvaelgere paa fanebladet 'Tilknyt lag'."""
        for rolle, combo in self.rolleCombos.items():
            if skema.harGeometri(rolle):
                combo.setFilters(Qgis.LayerFilter.PointLayer)
            else:
                combo.setFilters(Qgis.LayerFilter.NoGeometry)
            combo.setAllowEmptyLayer(True, "<ikke valgt>")
            combo.setCurrentIndex(0)
            combo.layerChanged.connect(self.validerTilknytning)

