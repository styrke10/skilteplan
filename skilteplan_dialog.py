FORM_CLASS, _ = uic.loadUiType(os.path.join(
    os.path.dirname(__file__), 'skilteplan_dialog_base.ui'))


class skilteplanDialog(QtWidgets.QDialog, FORM_CLASS):
    connectiondict = {}

    def __init__(self, parent=None):

        super(skilteplanDialog, self).__init__(parent)

        self.setupUi(self)

        # Load Postgres connections to combobox
        self.loadConnectionList()

        # Connect the file changed signal to the enable button slot
        self.cmbConnections.currentIndexChanged.connect(self.setEnableBtnState)
        self.path_sign_graphics.fileChanged.connect(self.setEnableBtnState)
        
        # Connect the layer changed signal to the update slot
        self.snaplayers.layerChanged.connect(self.updateFieldComboBox)
        
        self.signList.currentItemChanged.connect(self.changePreview)
        self.btnAddSign.clicked.connect(self.addSign)
        self.btnEditSign.clicked.connect(self.editSign)
        self.btnDeleteSign.clicked.connect(self.deleteSign)
        #self.btnInstructions.clicked.connect(self.openInstructions)
        

    def loadConnectionList(self):
        # Get the provider registry instance
        provider_registry = QgsProviderRegistry.instance()

        # List all available providers
        providers = provider_registry.providerList()

        # Print the supported data sources for each provider
        for provider_key in providers:
            if provider_key == 'postgres':
                provider_metadata = provider_registry.providerMetadata(provider_key)
                
                provider_connections = provider_metadata.connections()
                for pc_name, connection in provider_connections.items():
                    self.cmbConnections.addItem(pc_name)
                    self.connectiondict[pc_name] = connection.uri()

    def updateFieldComboBox(self):
        # Get the selected layer
        layer = self.snaplayers.currentLayer()

        # Set the layer for the field combo box
        self.vejkode.setLayer(layer)
        self.vejnavn.setLayer(layer)

    def setEnableBtnState(self):
        # Check if relevant fields have been filled out
        if self.path_sign_graphics.filePath() and self.cmbConnections.currentIndex() > -1:
            self.btnPrepareProject.setEnabled(True)
        else:
            self.btnPrepareProject.setEnabled(False)

    def fillSignList(self):
        # Find skiltetyper table
        #QgsMessageLog.logMessage("Adding signs", tag="skilteplan", level=Qgis.Info )
        signTable = None
        self.signNamesList = []
        for layer in QgsProject.instance().mapLayers().values():
            if layer.name() == "skiltetyper":
                #QgsMessageLog.logMessage("Found 'skiltetyper'", tag="skilteplan", level=Qgis.Info )
                signTable = layer
                break

        # Check if the layer is valid
        if signTable: 
            if signTable.isValid():
                #QgsMessageLog.logMessage('Sign DB loaded successfully', tag="skilteplan", level=Qgis.Info )
                # Empty sign list if any content exists
                current = self.signList.currentRow()
                self.signList.clear()
                self.signNamesList.clear()
            
                # Iterate over features in the layer
                for feature in signTable.getFeatures():
                    item = "{}\t{}".format(feature["skiltenavn"],feature["skiltebeskrivelse"])
                    self.signList.addItem(item)
                    self.signNamesList.append(feature["skiltenavn"])
                
                if current != -1:
                    self.signList.setCurrentRow(current)
                else:
                    self.signList.setCurrentRow(0)
            
    def changePreview(self):
        if self.signList.currentItem():
            #QgsMessageLog.logMessage('Current item changed: {}'.format(self.signList.currentItem().text()), tag="skilteplan", level=Qgis.Info )
            name = self.signList.currentItem().text().split("\t")[0]
            img_path = os.path.join(self.path_sign_graphics.filePath(),'.'.join((name,'svg')))
            self.previewSign(img_path)
    
    def previewSign(self,path):
        #QgsMessageLog.logMessage('Displaying sign: {}'.format(path), tag="skilteplan", level=Qgis.Info )
        # Create a QGraphicsScene
        scene = QGraphicsScene(self)
        self.signView.setScene(scene)

        # Load the SVG file into a QGraphicsSvgItem
        svg_item = QGraphicsSvgItem(path)
        scene.addItem(svg_item)

        # Set the view to fit the SVG item
        self.signView.fitInView(svg_item, Qt.KeepAspectRatio) #, mode=1)
        self.signView.show()

    def addSign(self):
        QgsMessageLog.logMessage("Initiate addsign", tag="skilteplan", level=Qgis.Info )
        signFile = QFileDialog.getOpenFileName(self, "Vælg fil m. skiltegrafik","", '*.svg')[0]
        if signFile:
            #QgsMessageLog.logMessage("Opening '{}'".format(signFile), tag="skilteplan", level=Qgis.Info )
            self.dlg = skilteplanAddSignDialog()
            self.dlg.addSignFile(signFile,self)
            self.dlg.show()

    def editSign(self):
        #QgsMessageLog.logMessage('Trying to edit sign: {}'.format(self.signList.currentItem().text()), tag="skilteplan", level=Qgis.Info )
        name = self.signList.currentItem().text().split("\t")[0]
        desc = self.signList.currentItem().text().split("\t")[1]
        #QgsMessageLog.logMessage("Deleting sign '{}'".format(name), tag="skilteplan", level=Qgis.Info )

        self.dlg = skilteplanAddSignDialog()
        self.dlg.editSignFile(name,self)
        self.dlg.show()

    def deleteSign(self):
        #QgsMessageLog.logMessage('Trying to delete sign: {}'.format(self.signList.currentItem().text()), tag="skilteplan", level=Qgis.Info )
        found = False
        for layer in QgsProject.instance().mapLayers().values():
            if layer.name() == "skiltetyper":
                found = True
                break
        
        if found:
            name = self.signList.currentItem().text().split("\t")[0]
            desc = self.signList.currentItem().text().split("\t")[1]
            #QgsMessageLog.logMessage("Deleting sign '{}'".format(name), tag="skilteplan", level=Qgis.Info )

            layer.startEditing()
            request = QgsFeatureRequest().setFilterExpression('"skiltenavn" = \'{}\''.format(name))

            # Iterate over matching features and delete them
            for feature in layer.getFeatures(request):
                msgBox = QMessageBox()
                msgBox.setIcon(QMessageBox.Warning)
                msgBox.setText("Vil du slette skilt '{} - {}'".format(name,desc))
                msgBox.setStandardButtons(QMessageBox.Yes | QMessageBox.No)
                response = msgBox.exec_()
                if response == QMessageBox.Yes:
                    layer.deleteFeature(feature.id())
                    # Delete SVG file
                    delpath = os.path.join(self.path_sign_graphics.filePath(),'.'.join((name,'svg')))
                    if os.path.isfile(delpath):
                        os.remove(delpath)
                    #QgsMessageLog.logMessage("Sign deleted! ({})".format(delpath), tag="skilteplan", level=Qgis.Info )

            layer.commitChanges()
            
            # Refresh sign list on parent dialog
            self.fillSignList()

